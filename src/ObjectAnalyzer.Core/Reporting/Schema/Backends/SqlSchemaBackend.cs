using System.Globalization;
using System.Text;
using ObjectAnalyzer.Data;

namespace ObjectAnalyzer.Reporting;

public sealed class SqlSchemaBackend : ISchemaBackend
{
    public string Format => "sql";
    public SchemaExportResult Generate(SchemaDocument document, SchemaExportOptions options)
    {
        string dialect = options.SqlDialect.ToLowerInvariant() switch
        { "postgres" or "postgresql" or "pg" => "postgres", "mysql" => "mysql", "sqlite" => "sqlite", "sqlserver" or "mssql" => "sqlserver", _ => throw new ArgumentException("Unknown SQL dialect.", nameof(options)) };
        var context = new SchemaRenderContext(document, options);
        var names = SchemaNamePlan.Create(document, SchemaNamingTarget.Sql, options.RootName);
        var lines = new List<string>(); var checks = new List<string>();
        foreach (var property in document.Root.Properties.OrderBy(item => item.Name, StringComparer.Ordinal))
        {
            string column = names.PropertyName(document.Root, property.Name);
            if (column != property.Name) context.Note("sql-identifier-renamed", property.Name, "Identifier was sanitized or disambiguated; use the exported column name.");
            if (property.Presence != SchemaPresence.Required || property.Type.AllowsNull)
                context.Note("sql-null-presence", property.Name, "SQL NULL does not preserve the distinction between a missing JSON property and an explicit null.");
            string quoted = Quote(column, dialect);
            string type = Type(property.Type, property.Name, dialect, context);
            bool required = property.Presence == SchemaPresence.Required && !property.Type.AllowsNull && !property.Type.HasUnknownValues;
            lines.Add(quoted + " " + type + (required ? " NOT NULL" : ""));
            if (property.Type.EnumValues.Length > 0 && property.Type.Kinds.Any(kind => kind is RecordValueKind.Object or RecordValueKind.Array))
                context.Note("sql-enum-omitted", property.Name, "Structured enums require application validation; SQL JSON storage has no portable exact-value CHECK.");
            if (property.Type.EnumValues.Length > 0 && !property.Type.Kinds.Any(kind => kind is RecordValueKind.Object or RecordValueKind.Array))
            {
                var literals = property.Type.EnumValues.Select(value => Literal(value, dialect)).ToArray();
                if (literals.Any(value => value is null)) context.Note("sql-enum-omitted", property.Name, "Unsupported enum values cannot form a portable SQL CHECK; no partial constraint is emitted.");
                else checks.Add("CHECK (" + quoted + " IN (" + string.Join(", ", literals) + "))");
            }
        }
        if (lines.Count == 0)
        { lines.Add(Quote("_document", dialect) + " " + JsonType(dialect)); context.Note("sql-empty-object", "", "SQL tables need a column; empty objects are stored in a JSON/text document column."); }
        lines.AddRange(checks);
        var output = new StringBuilder("CREATE TABLE ");
        // Table spelling remains the caller's spelling, independently from type identifiers.
        output.Append(Quote(SchemaNamePlan.Identifier(options.RootName, false), dialect)).AppendLine(" (");
        for (int i = 0; i < lines.Count; i++) output.Append("  ").Append(lines[i]).AppendLine(i == lines.Count - 1 ? "" : ",");
        output.AppendLine(");");
        return context.Finish("-- <auto-generated>\n" + context.Comments("--") + output);
    }
    private static string Type(SchemaType type, string path, string dialect, SchemaRenderContext context)
    {
        var kinds = type.Kinds.Where(kind => kind != RecordValueKind.Null).ToArray();
        if (type.HasUnknownValues || kinds.Length != 1)
        { context.Note("sql-json-fallback", path, "Union or unknown values use JSON storage; null and missing properties cannot be distinguished by SQL NULL alone."); return JsonType(dialect); }
        if (kinds[0] is RecordValueKind.Array or RecordValueKind.Object) return JsonType(dialect);
        if (kinds[0] == RecordValueKind.Number)
        {
            if (type.Numeric is { Integral: true, FitsInt64: true }) return dialect == "sqlite" ? "INTEGER" : "BIGINT";
            if (type.Numeric?.FitsDouble == true) return dialect switch { "sqlite" => "REAL", "mysql" => "DOUBLE", "sqlserver" => "FLOAT", _ => "DOUBLE PRECISION" };
            if (type.Numeric is { FitsDecimal: true, IntegerDigits: { } digits, Scale: { } scale } && dialect != "sqlite" && (long)digits + scale <= (dialect == "mysql" ? 65 : 38))
                return "DECIMAL(" + Math.Max(1, digits + scale).ToString(CultureInfo.InvariantCulture) + "," + scale.ToString(CultureInfo.InvariantCulture) + ")";
            context.Note("sql-number-text", path, "The SQL numeric type cannot guarantee this number's precision or scale; using exact numeric text.");
            return Text(dialect);
        }
        if (kinds[0] == RecordValueKind.Binary) return dialect switch { "postgres" => "BYTEA", "mysql" => "LONGBLOB", "sqlserver" => "VARBINARY(MAX)", _ => "BLOB" };
        if (kinds[0] == RecordValueKind.Boolean) return dialect switch { "sqlite" => "INTEGER", "mysql" => "TINYINT(1)", "sqlserver" => "BIT", _ => "BOOLEAN" };
        if (kinds[0] is RecordValueKind.DateTime or RecordValueKind.DateTimeOffset || type.VerifiedSemanticTypes.Length == 1 && type.VerifiedSemanticTypes[0] == "DateTime")
            return dialect switch { "sqlite" => "TEXT", "sqlserver" => "DATETIME2", _ => "TIMESTAMP" };
        if (kinds[0] == RecordValueKind.Guid || type.VerifiedSemanticTypes.Length == 1 && type.VerifiedSemanticTypes[0] == "UUID")
            return dialect switch { "sqlite" => "TEXT", "mysql" => "CHAR(36)", "sqlserver" => "UNIQUEIDENTIFIER", _ => "UUID" };
        return Text(dialect);
    }
    private static string Text(string dialect) => dialect == "sqlserver" ? "NVARCHAR(MAX)" : "TEXT";
    private static string JsonType(string dialect) => dialect switch { "postgres" => "JSONB", "mysql" => "JSON", _ => Text(dialect) };
    private static string Quote(string name, string dialect) => dialect switch
    { "mysql" => "\x60" + name.Replace("\x60", "\x60\x60", StringComparison.Ordinal) + "\x60", "sqlserver" => "[" + name.Replace("]", "]]", StringComparison.Ordinal) + "]", _ => "\"" + name.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"" };
    private static string? Literal(RecordValue value, string dialect) => value.Kind switch
    {
        RecordValueKind.String => "'" + value.Scalar.Replace("'", "''", StringComparison.Ordinal) + "'",
        RecordValueKind.Null => "NULL", RecordValueKind.Number => value.Scalar,
        RecordValueKind.Boolean => dialect == "postgres" ? value.Scalar == "true" ? "TRUE" : "FALSE" : value.Scalar == "true" ? "1" : "0", _ => null
    };
}
