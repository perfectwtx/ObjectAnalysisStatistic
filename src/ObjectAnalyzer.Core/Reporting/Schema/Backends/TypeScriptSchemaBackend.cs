using System.Text;
using System.Text.Json;
using ObjectAnalyzer.Data;

namespace ObjectAnalyzer.Reporting;

public sealed class TypeScriptSchemaBackend : ISchemaBackend
{
    public string Format => "typescript";
    public SchemaExportResult Generate(SchemaDocument document, SchemaExportOptions options)
    {
        var context = new SchemaRenderContext(document, options);
        var names = SchemaNamePlan.Create(document, SchemaNamingTarget.TypeScript, options.RootName);
        var output = new StringBuilder();
        foreach (var node in names.Objects)
        {
            output.Append("export interface ").Append(names.TypeName(node)).AppendLine(" {");
            foreach (var property in node.Properties.OrderBy(item => item.Name, StringComparer.Ordinal))
                output.Append("  ").Append(Property(property.Name)).Append(property.Presence == SchemaPresence.Required ? "" : "?")
                    .Append(": ").Append(Type(property.Type, SchemaRenderContext.Child(names.SourcePath(node), property.Name), names, context)).AppendLine(";");
            output.AppendLine("  [key: string]: unknown;");
            output.AppendLine("}").AppendLine();
        }
        return context.Finish("// <auto-generated>\n" + context.Comments("//") + output);
    }
    private static string Property(string name) => name.Length > 0 && (char.IsAsciiLetter(name[0]) || name[0] is '_' or '$')
        && name.All(ch => char.IsAsciiLetterOrDigit(ch) || ch is '_' or '$') ? name : JsonSerializer.Serialize(name);
    private static string Type(SchemaType node, string path, SchemaNamePlan names, SchemaRenderContext context)
    {
        string structural = StructuralType(node, path, names, context);
        if (node.EnumValues.Length == 0) return structural;
        if (node.EnumValues.Any(value => value.Kind is RecordValueKind.Object or RecordValueKind.Array || value.Kind == RecordValueKind.Number && !value.FitsDouble))
        { context.Note("typescript-enum-unenforced", path, "Structured or arbitrary-precision enums cannot be represented exactly by these TypeScript literals; structural type retained."); return structural; }
        return "(" + structural + ") & (" + string.Join(" | ", node.EnumValues.Select(value => value.ToJsonString())) + ")";
    }
    private static string StructuralType(SchemaType node, string path, SchemaNamePlan names, SchemaRenderContext context)
    {
        if (node.HasUnknownValues)
        { context.Note("typescript-unknown", path, "Incomplete type evidence uses unknown rather than any or a guessed primitive."); return "unknown"; }
        var variants = new List<string>();
        foreach (var kind in node.Kinds)
            variants.Add(kind switch
            {
                RecordValueKind.Null => "null", RecordValueKind.Boolean => "boolean", RecordValueKind.Object => names.TypeName(node),
                RecordValueKind.Number => Number(node, path, context),
                RecordValueKind.Array => Array(node, path, names, context), _ => "string"
            });
        if (variants.Count == 0) return "unknown";
        return string.Join(" | ", variants.Distinct());
    }
    private static string Number(SchemaType node, string path, SchemaRenderContext context)
    {
        if (node.Numeric?.FitsDouble != true || node.Numeric.Integral && (node.Numeric.IntegerDigits is null or > 15))
            context.Note("typescript-number-precision", path, "JavaScript number cannot guarantee exact decimal or large-integer values; use an exact-number JSON codec when required.");
        return "number";
    }
    private static string Array(SchemaType node, string path, SchemaNamePlan names, SchemaRenderContext context)
    {
        if (node.Element is null)
        { context.Note("array-element-unknown", path, "Empty or unobserved array elements remain unknown."); return "unknown[]"; }
        string element = Type(node.Element, path + "[]", names, context);
        return (element.Contains(" | ", StringComparison.Ordinal) ? "(" + element + ")" : element) + "[]";
    }
}
