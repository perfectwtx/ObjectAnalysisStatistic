using System.Globalization;
using System.Text;
using System.Text.Json;
using ObjectAnalyzer.Data;

namespace ObjectAnalyzer.Reporting;

public sealed class ProtobufSchemaBackend : ISchemaBackend
{
    public string Format => "protobuf";
    public SchemaExportResult Generate(SchemaDocument document, SchemaExportOptions options)
    {
        var context = new SchemaRenderContext(document, options);
        var names = SchemaNamePlan.Create(document, SchemaNamingTarget.Protobuf, options.RootName);
        var output = new StringBuilder("syntax = \"proto3\";\npackage object_analyzer.generated;\n\n");
        foreach (var node in names.Objects)
        {
            output.Append("message ").Append(names.TypeName(node)).AppendLine(" {");
            var tags = new HashSet<uint>();
            foreach (var property in node.Properties.OrderBy(item => item.Name, StringComparer.Ordinal))
            {
                string type = Type(property.Type, SchemaRenderContext.Child(names.SourcePath(node), property.Name), names, context, out bool repeated);
                if (property.Type.AllowsNull)
                    context.Note("protobuf-null-presence", SchemaRenderContext.Child(names.SourcePath(node), property.Name), "Proto3 presence does not distinguish an explicit JSON null from a missing value.");
                if (repeated && property.Presence != SchemaPresence.Required)
                    context.Note("protobuf-array-presence", SchemaRenderContext.Child(names.SourcePath(node), property.Name), "Repeated fields cannot distinguish an absent array from an empty array.");
                string modifier = repeated ? "repeated " : property.Presence != SchemaPresence.Required || property.Type.AllowsNull ? "optional " : "";
                output.Append("  ").Append(modifier).Append(type).Append(' ').Append(names.PropertyName(node, property.Name)).Append(" = ")
                    .Append(Tag(property.Name, tags).ToString(CultureInfo.InvariantCulture)).Append(" [json_name = ").Append(JsonSerializer.Serialize(property.Name)).AppendLine("];");
            }
            output.AppendLine("}").AppendLine();
        }
        return context.Finish("// <auto-generated>\n" + context.Comments("//") + output);
    }
    private static string Type(SchemaType type, string path, SchemaNamePlan names, SchemaRenderContext context, out bool repeated)
    {
        if (type.EnumValues.Length > 0) context.Note("protobuf-enum-unenforced", path, "Declared JSON enum constraints are not enforced by this protobuf field type.");
        repeated = false;
        var kinds = type.Kinds.Where(kind => kind != RecordValueKind.Null).ToArray();
        if (type.HasUnknownValues || type.ShapeIncomplete || kinds.Length != 1) return JsonText(path, context);
        switch (kinds[0])
        {
            case RecordValueKind.Object: return names.TypeName(type);
            case RecordValueKind.Array:
                if (type.Element is null || type.Element.Kinds.Contains(RecordValueKind.Array)) return JsonText(path, context);
                repeated = true;
                if (type.Element.AllowsNull) context.Note("protobuf-null-element", path, "Nullable elements use JSON text rather than nullable protobuf scalar elements.");
                return type.Element.AllowsNull ? JsonText(path + "[]", context) : Type(type.Element, path + "[]", names, context, out _);
            case RecordValueKind.Number:
                if (type.Numeric is { Integral: true, FitsInt64: true }) return "int64";
                if (type.Numeric?.FitsDouble == true) return "double";
                context.Note("protobuf-number-precision", path, "Decimal and arbitrary-precision numbers are encoded as exact numeric text."); return "string";
            case RecordValueKind.Boolean: return "bool";
            case RecordValueKind.Binary: return "bytes";
            default: return "string";
        }
    }
    private static string JsonText(string path, SchemaRenderContext context)
    {
        context.Note("protobuf-json-text", path, "Union, unknown or nested-array values require JSON text in a string field; JSON wire shape changes.");
        return "string";
    }
    private static uint Tag(string name, HashSet<uint> used)
    {
        uint hash = 2166136261;
        foreach (byte value in Encoding.UTF8.GetBytes(name)) hash = unchecked((hash ^ value) * 16777619);
        uint tag = hash % 536870911 + 1;
        while (true)
        {
            if (tag is >= 19000 and <= 19999) tag = 20000;
            if (used.Add(tag)) return tag;
            tag = tag == 536870911 ? 1 : tag + 1;
        }
    }
}
