using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;

namespace ObjectAnalyzer.Reporting;

public static partial class SchemaExporter
{

    // ─────────────────────────────────────────────
    //  gRPC Protobuf 3 (.proto) Generator
    // ─────────────────────────────────────────────

    /// <summary>
    /// Generates gRPC Protobuf 3 syntax message definitions (.proto).
    /// Un-flattens nested object DTOs into protobuf messages with field tag numbers.
    /// </summary>
    public static string GenerateProtobuf(AnalysisResult result, string messageName = "GeneratedSchema")
    {
        var rootTree = BuildSchemaTree(result);
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// 由 ObjectAnalyzer 自动生成的 gRPC Protobuf 3 消息定义");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("syntax = \"proto3\";");
        sb.AppendLine();
        sb.AppendLine("package object_analyzer.generated;");
        sb.AppendLine();

        var messageList = new List<(string name, SchemaNode node)>();
        CollectProtobufMessages(rootTree, messageName, messageList);

        foreach (var (name, node) in messageList)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"message {name} {{");
            int fieldTag = 1;

            foreach (var propKvp in node.Properties)
            {
                string propName = propKvp.Key;
                var childNode = propKvp.Value;
                string sanitizedProp = SanitizeIdentifier(propName);
                string protoField = SanitizeProtobufFieldName(propName);

                if (childNode.Kind == "Object")
                {
                    string dtoType = $"{sanitizedProp}Dto";
                    sb.AppendLine(CultureInfo.InvariantCulture, $"  {dtoType} {protoField} = {fieldTag++};");
                }
                else if (childNode.Kind == "Array")
                {
                    string elemType = childNode.ElementNode?.Kind == "Object"
                        ? $"{sanitizedProp}ItemDto"
                        : MapToProtobufBaseType(childNode.ElementNode);
                    sb.AppendLine(CultureInfo.InvariantCulture, $"  repeated {elemType} {protoField} = {fieldTag++};");
                }
                else
                {
                    string baseType = MapToProtobufBaseType(childNode);
                    sb.AppendLine(CultureInfo.InvariantCulture, $"  {baseType} {protoField} = {fieldTag++};");
                }
            }

            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    private static void CollectProtobufMessages(SchemaNode node, string messageName, List<(string name, SchemaNode node)> messageList)
    {
        foreach (var propKvp in node.Properties)
        {
            var child = propKvp.Value;
            string sanitizedProp = SanitizeIdentifier(propKvp.Key);
            if (child.Kind == "Object")
            {
                CollectProtobufMessages(child, $"{sanitizedProp}Dto", messageList);
            }
            else if (child.Kind == "Array" && child.ElementNode?.Kind == "Object")
            {
                CollectProtobufMessages(child.ElementNode, $"{sanitizedProp}ItemDto", messageList);
            }
        }
        messageList.Add((messageName, node));
    }

    private static string MapToProtobufBaseType(SchemaNode? node)
    {
        if (node == null) return "string";
        return node.CSharpBaseType switch
        {
            "long" => "int64",
            "double" => "double",
            "bool" => "bool",
            _ => "string"
        };
    }

    private static string SanitizeProtobufFieldName(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return "field";
        string sanitized = new string(name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
        if (char.IsDigit(sanitized[0])) sanitized = "_" + sanitized;
        return sanitized;
    }
}
