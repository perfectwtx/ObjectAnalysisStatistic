using System.Globalization;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;

namespace ObjectAnalyzer.Reporting;

public static partial class SchemaExporter
{

    // ─────────────────────────────────────────────
    //  SQL DDL Generator
    // ─────────────────────────────────────────────

    /// <summary>
    /// Generates a CREATE TABLE statement for the requested SQL dialect (postgres / mysql / sqlite).
    /// Root-level object/array fields collapse into a dialect-appropriate JSON column;
    /// primitive fields map to typed columns (BIGINT / TEXT / BOOLEAN / TIMESTAMP / UUID ...).
    /// NOT NULL is emitted when a field is present across all objects (coverage 1.0) with no observed null.
    /// A CHECK (col IN (...)) constraint is emitted when the field carries enum rule values.
    /// </summary>
    public static string GenerateSql(AnalysisResult result, string dialect = "postgres", string tableName = "GeneratedSchema")
    {
        var rootTree = BuildSchemaTree(result);
        string normalized = dialect.ToLowerInvariant();
        string quote = normalized switch { "mysql" => "`", "sqlserver" => "[", _ => "\"" };
        string safeTable = SanitizeSqlIdentifier(tableName);
        if (string.IsNullOrEmpty(safeTable)) safeTable = "GeneratedSchema";

        var columnLines = new List<string>();
        var checkLines = new List<string>();
        var usedColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var propKvp in rootTree.Properties)
        {
            var child = propKvp.Value;
            bool isJson = child.Kind == "Object" || child.Kind == "Array";
            string sqlType = isJson ? MapToSqlJsonType(normalized) : MapToSqlType(child.Field, normalized);

            string baseCol = SanitizeSqlIdentifier(propKvp.Key);
            if (string.IsNullOrEmpty(baseCol)) baseCol = "column";
            string colName = baseCol;
            int suffix = 2;
            while (!usedColumns.Add(colName)) colName = baseCol + "_" + suffix++.ToString(CultureInfo.InvariantCulture);
            string col = QuoteIdentifier(colName, quote);

            bool notNull = child.Field != null && child.Field.Coverage >= 1.0 && !child.Field.NullAppeared;
            columnLines.Add($"{col} {sqlType}{(notNull ? " NOT NULL" : "")}");

            if (!isJson && child.Field?.AppliedRule?.EnumValues is { Count: > 0 } enumValues)
            {
                var literals = enumValues
                    .Select(e => FormatSqlLiteral(e, normalized))
                    .Distinct(StringComparer.Ordinal)
                    .ToList();
                if (literals.Count > 0)
                {
                    checkLines.Add($"CHECK ({col} IN ({string.Join(", ", literals)}))");
                }
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("-- <auto-generated>");
        sb.AppendLine(CultureInfo.InvariantCulture, $"-- ObjectAnalyzer 自动生成的 {MapDialectDisplayName(normalized)} Schema");
        sb.AppendLine("-- </auto-generated>");
        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"CREATE TABLE {QuoteIdentifier(safeTable, quote)} (");

        var body = new List<string>();
        body.AddRange(columnLines);
        body.AddRange(checkLines);
        for (int i = 0; i < body.Count; i++)
        {
            string suffix = i < body.Count - 1 ? "," : "";
            sb.AppendLine(CultureInfo.InvariantCulture, $"  {body[i]}{suffix}");
        }

        sb.AppendLine(");");
        return sb.ToString();
    }

    // ─────────────────────────────────────────────
    //  SQL Type Mapping Helpers
    // ─────────────────────────────────────────────

    private static string MapToSqlType(FieldStatistic? field, string dialect)
    {
        if (field == null) return DefaultStringType(dialect);
        if (field.SemanticType == "DateTime") return dialect switch { "sqlite" => "TEXT", "sqlserver" => "DATETIME2", _ => "TIMESTAMP" };
        if (field.SemanticType == "UUID")
        {
            return dialect switch
            {
                "mysql" => "CHAR(36)",
                "sqlite" => "TEXT",
                "sqlserver" => "UNIQUEIDENTIFIER",
                _ => "UUID"
            };
        }

        return field.PrimaryType switch
        {
            "Number" => MapToSqlNumberType(field, dialect),
            "Boolean" => MapToSqlBooleanType(dialect),
            _ => DefaultStringType(dialect)
        };
    }

    private static string MapToSqlNumberType(FieldStatistic field, string dialect)
    {
        bool fractional = field.AvgNumber.HasValue && field.AvgNumber.Value % 1 != 0;
        return dialect switch
        {
            "mysql" => fractional ? "DOUBLE" : "BIGINT",
            "sqlite" => fractional ? "REAL" : "INTEGER",
            "sqlserver" => fractional ? "FLOAT" : "BIGINT",
            _ => fractional ? "DOUBLE PRECISION" : "BIGINT"
        };
    }

    private static string MapToSqlBooleanType(string dialect) => dialect switch
    {
        "mysql" => "TINYINT(1)",
        "sqlite" => "INTEGER",
        "sqlserver" => "BIT",
        _ => "BOOLEAN"
    };

    private static string DefaultStringType(string dialect) => dialect == "sqlserver" ? "NVARCHAR(MAX)" : "TEXT";

    private static string MapToSqlJsonType(string dialect) => dialect switch
    {
        "mysql" => "JSON",
        "sqlite" => "TEXT",
        "sqlserver" => "NVARCHAR(MAX)",
        _ => "JSONB"
    };

    private static string MapDialectDisplayName(string dialect) => dialect switch
    {
        "mysql" => "MySQL",
        "sqlite" => "SQLite",
        "sqlserver" => "SQL Server",
        _ => "PostgreSQL"
    };

    private static string FormatSqlLiteral(JsonElement element, string dialect)
    {
        switch (element.ValueKind)
        {
            case JsonValueKind.String:
                return "'" + (element.GetString() ?? "").Replace("'", "''") + "'";
            case JsonValueKind.Number:
                return element.GetRawText() ?? "0";
            case JsonValueKind.True:
            case JsonValueKind.False:
                bool b = element.GetBoolean();
                return dialect == "postgres" ? (b ? "TRUE" : "FALSE") : (b ? "1" : "0");
            default:
                return "NULL";
        }
    }

    private static string SanitizeSqlIdentifier(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return "";
        string sanitized = new string(name.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
        if (char.IsDigit(sanitized[0])) sanitized = "_" + sanitized;
        return sanitized;
    }

    private static string QuoteIdentifier(string name, string quoteChar)
    {
        if (quoteChar == "`") return "`" + name.Replace("`", "``") + "`";
        if (quoteChar == "[") return "[" + name.Replace("]", "]]") + "]";
        return "\"" + name.Replace("\"", "\"\"") + "\"";
    }

    private static string SqlTableNameFromPath(string outputPath)
    {
        if (string.IsNullOrWhiteSpace(outputPath)) return "GeneratedSchema";
        string name = SanitizeSqlIdentifier(Path.GetFileNameWithoutExtension(outputPath));
        if (name.EndsWith("_schema", StringComparison.OrdinalIgnoreCase))
        {
            name = name.Substring(0, name.Length - "_schema".Length);
        }
        return string.IsNullOrEmpty(name) ? "GeneratedSchema" : name;
    }
}
