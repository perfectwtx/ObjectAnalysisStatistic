using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using Microsoft.CodeAnalysis;

namespace ObjectAnalyzer.Reporting;

public static partial class SchemaExporter
{

    // ─────────────────────────────────────────────
    //  OpenAPI 3.0 (Swagger) Generator
    // ─────────────────────────────────────────────

    /// <summary>
    /// Generates OpenAPI 3.0.3 components/schemas specification in JSON format using System.Text.Json.Nodes DOM.
    /// Un-flattens nested object DTOs into reusable component schemas referenced via $ref.
    /// </summary>
    public static string GenerateOpenApiJson(AnalysisResult result, string title = "GeneratedSchema")
    {
        var rootTree = BuildSchemaTree(result);
        var schemasObj = new JsonObject();

        BuildOpenApiJsonSchemas(rootTree, title, schemasObj);

        var openApiDoc = new JsonObject
        {
            ["openapi"] = "3.0.3",
            ["info"] = new JsonObject
            {
                ["title"] = $"{title} API Models",
                ["version"] = "1.0.0",
                ["description"] = "由 ObjectAnalyzer 自动生成的 OpenAPI 3.0 规范组件数据模型"
            },
            ["components"] = new JsonObject
            {
                ["schemas"] = schemasObj
            }
        };

        return openApiDoc.ToJsonString(JsonSharedOptions.Write);
    }

    /// <summary>
    /// Generates OpenAPI 3.0.3 specification in clean YAML format.
    /// Un-flattens nested object DTOs into reusable component schemas referenced via $ref.
    /// </summary>
    public static string GenerateOpenApiYaml(AnalysisResult result, string title = "GeneratedSchema")
    {
        var rootTree = BuildSchemaTree(result);
        var sb = new StringBuilder();

        sb.AppendLine("# <auto-generated>");
        sb.AppendLine("# 由 ObjectAnalyzer 自动生成的 OpenAPI 3.0 (YAML) 规范定义");
        sb.AppendLine("# </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("openapi: 3.0.3");
        sb.AppendLine("info:");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  title: {title} API Models");
        sb.AppendLine("  version: 1.0.0");
        sb.AppendLine("  description: 由 ObjectAnalyzer 自动生成的 OpenAPI 3.0 规范组件数据模型");
        sb.AppendLine("components:");
        sb.AppendLine("  schemas:");

        var schemaList = new List<(string name, SchemaNode node)>();
        CollectOpenApiYamlSchemas(rootTree, title, schemaList);

        foreach (var (name, node) in schemaList)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"    {name}:");
            sb.AppendLine("      type: object");

            var reqList = node.Properties.Where(p => !p.Value.IsNullable).Select(p => p.Key).ToList();
            if (reqList.Count > 0)
            {
                sb.AppendLine("      required:");
                foreach (var req in reqList)
                {
                    sb.AppendLine(CultureInfo.InvariantCulture, $"        - {req}");
                }
            }

            sb.AppendLine("      properties:");
            foreach (var propKvp in node.Properties)
            {
                string propName = propKvp.Key;
                var childNode = propKvp.Value;
                string sanitizedProp = SanitizeIdentifier(propName);

                sb.AppendLine(CultureInfo.InvariantCulture, $"        {propName}:");
                if (childNode.Kind == "Object")
                {
                    sb.AppendLine(CultureInfo.InvariantCulture, $"          $ref: '#/components/schemas/{sanitizedProp}Dto'");
                    if (childNode.IsNullable) sb.AppendLine("          nullable: true");
                }
                else if (childNode.Kind == "Array")
                {
                    sb.AppendLine("          type: array");
                    sb.AppendLine("          items:");
                    if (childNode.ElementNode?.Kind == "Object")
                    {
                        sb.AppendLine(CultureInfo.InvariantCulture, $"            $ref: '#/components/schemas/{sanitizedProp}ItemDto'");
                    }
                    else
                    {
                        string elemType = childNode.ElementNode?.JsonSchemaBaseType ?? "string";
                        sb.AppendLine(CultureInfo.InvariantCulture, $"            type: {elemType}");
                        if (childNode.ElementNode?.Format != null)
                        {
                            sb.AppendLine(CultureInfo.InvariantCulture, $"            format: {childNode.ElementNode.Format}");
                        }
                    }
                    if (childNode.IsNullable) sb.AppendLine("          nullable: true");
                }
                else
                {
                    sb.AppendLine(CultureInfo.InvariantCulture, $"          type: {childNode.JsonSchemaBaseType}");
                    if (childNode.Format != null)
                    {
                        sb.AppendLine(CultureInfo.InvariantCulture, $"          format: {childNode.Format}");
                    }
                    if (childNode.IsNullable) sb.AppendLine("          nullable: true");
                }
            }
        }

        return sb.ToString();
    }

    private static void BuildOpenApiJsonSchemas(SchemaNode node, string schemaName, JsonObject schemasObj)
    {
        foreach (var propKvp in node.Properties)
        {
            var child = propKvp.Value;
            string sanitizedProp = SanitizeIdentifier(propKvp.Key);
            if (child.Kind == "Object")
            {
                BuildOpenApiJsonSchemas(child, $"{sanitizedProp}Dto", schemasObj);
            }
            else if (child.Kind == "Array" && child.ElementNode?.Kind == "Object")
            {
                BuildOpenApiJsonSchemas(child.ElementNode, $"{sanitizedProp}ItemDto", schemasObj);
            }
        }

        var schemaObj = new JsonObject
        {
            ["type"] = "object",
            ["properties"] = BuildOpenApiProperties(node),
            ["required"] = BuildJsonSchemaRequired(node)
        };

        schemasObj[schemaName] = schemaObj;
    }

    private static JsonObject BuildOpenApiProperties(SchemaNode node)
    {
        var propsObj = new JsonObject();
        foreach (var propKvp in node.Properties)
        {
            string propName = propKvp.Key;
            var childNode = propKvp.Value;
            string sanitizedProp = SanitizeIdentifier(propName);
            var propDef = new JsonObject();

            if (childNode.Kind == "Object")
            {
                propDef["$ref"] = $"#/components/schemas/{sanitizedProp}Dto";
                if (childNode.IsNullable) propDef["nullable"] = true;
            }
            else if (childNode.Kind == "Array")
            {
                propDef["type"] = "array";
                var itemDef = new JsonObject();
                if (childNode.ElementNode?.Kind == "Object")
                {
                    itemDef["$ref"] = $"#/components/schemas/{sanitizedProp}ItemDto";
                }
                else
                {
                    itemDef["type"] = childNode.ElementNode?.JsonSchemaBaseType ?? "string";
                    if (childNode.ElementNode?.Format != null)
                        itemDef["format"] = childNode.ElementNode.Format;
                }
                propDef["items"] = itemDef;
                if (childNode.IsNullable) propDef["nullable"] = true;
            }
            else
            {
                propDef["type"] = childNode.JsonSchemaBaseType;
                if (childNode.Format != null)
                    propDef["format"] = childNode.Format;
                if (childNode.IsNullable)
                    propDef["nullable"] = true;
            }

            propsObj[propName] = propDef;
        }
        return propsObj;
    }

    private static void CollectOpenApiYamlSchemas(SchemaNode node, string schemaName, List<(string name, SchemaNode node)> schemaList)
    {
        foreach (var propKvp in node.Properties)
        {
            var child = propKvp.Value;
            string sanitizedProp = SanitizeIdentifier(propKvp.Key);
            if (child.Kind == "Object")
            {
                CollectOpenApiYamlSchemas(child, $"{sanitizedProp}Dto", schemaList);
            }
            else if (child.Kind == "Array" && child.ElementNode?.Kind == "Object")
            {
                CollectOpenApiYamlSchemas(child.ElementNode, $"{sanitizedProp}ItemDto", schemaList);
            }
        }
        schemaList.Add((schemaName, node));
    }
}
