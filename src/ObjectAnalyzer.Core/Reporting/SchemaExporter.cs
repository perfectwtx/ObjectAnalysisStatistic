    //  AST Tree Builder
    // ─────────────────────────────────────────────

    private static SchemaNode BuildSchemaTree(AnalysisResult result)
    {
        var root = new SchemaNode { NodeName = "Root", Kind = "Object" };

        foreach (var field in result.FieldStatistics)
        {
            string[] parts = field.FieldName.Split('.');
            SchemaNode current = root;

            for (int i = 0; i < parts.Length; i++)
            {
                string part = parts[i];
                bool isLast = (i == parts.Length - 1);

                // 解析段: "tags[0]" -> baseName="tags", arrayLevels=1; "matrix[0][0]" -> arrayLevels=2
                string baseName = part;
                int arrayLevels = 0;
                int bracket = part.IndexOf('[');
                if (bracket >= 0)
                {
                    baseName = part.Substring(0, bracket);
                    arrayLevels = part.Count(ch => ch == '[');
                }

                if (arrayLevels > 0)
                {
                    // 数组段
                    if (!current.Properties.TryGetValue(baseName, out var arrNode))
                    {
                        arrNode = new SchemaNode
                        {
                            NodeName = baseName,
                            Kind = "Array",
                            IsNullable = field.NullAppeared
                        };
                        current.Properties[baseName] = arrNode;
                    }

                    SchemaNode element = arrNode.ElementNode ??= new SchemaNode { NodeName = "Item", Kind = "Primitive" };

                    // 多层数组: "matrix[0][0]" -> 中间层元素本身也是数组
                    for (int level = 1; level < arrayLevels; level++)
                    {
                        if (element.Kind != "Array")
                        {
                            element.Kind = "Array";
                            element.Properties.Clear();
                        }
                        element.ElementNode ??= new SchemaNode { NodeName = "Item", Kind = "Primitive" };
                        element = element.ElementNode;
                    }

                    if (!isLast && element.Kind == "Primitive")
                    {
                        // 之后还有子段（如 "tags[0].name"）：元素升级为对象
                        element.Kind = "Object";
                    }

                    if (isLast)
                    {
                        ApplyFieldType(element, field);
                    }

                    current = element;
                }
                else
                {
                    // 普通对象段
                    if (!current.Properties.TryGetValue(part, out var objNode))
                    {
                        objNode = new SchemaNode
                        {
                            NodeName = part,
                            Kind = "Object",
                            IsNullable = isLast ? field.NullAppeared : (field.Coverage < 1.0 || field.NullAppeared)
                        };
                        current.Properties[part] = objNode;
                    }

                    if (isLast)
                    {
                        ApplyFieldType(objNode, field);
                    }

                    current = objNode;
                }
            }
        }

        return root;
    }

    /// <summary>
    /// 将叶节点字段的静态类型信息应用到 SchemaNode。
    /// 若节点已包含子属性（如先出现 "address.city" 又出现 "address"），保持对象形态，不做降级。
    /// </summary>
    private static void ApplyFieldType(SchemaNode node, FieldStatistic field)
    {
        node.IsNullable = field.NullAppeared;
        node.Field = field;

        switch (field.PrimaryType)
        {
            case "Object":
                node.Kind = "Object";
                break;

            case "Array":
                if (node.Properties.Count == 0)
                {
                    node.Kind = "Array";
                    node.ElementNode ??= new SchemaNode { NodeName = "Item", Kind = "Primitive" };
                    if (node.ElementNode.Properties.Count == 0 && node.ElementNode.Kind != "Object")
                    {
                        node.ElementNode.CSharpBaseType = "string";
                        node.ElementNode.TsBaseType = "string";
                        node.ElementNode.JsonSchemaBaseType = "string";
                        node.ElementNode.Format = null;
                    }
                }
                break;

            default:
                if (node.Properties.Count == 0)
                {
                    node.Kind = "Primitive";
                    node.CSharpBaseType = MapToCSharpBaseType(field);
                    node.TsBaseType = MapToTsBaseType(field);
                    node.JsonSchemaBaseType = MapToJsonSchemaBaseType(field, out string? fmt);
                    node.Format = fmt;
                }
                break;
        }
    }

    // ─────────────────────────────────────────────
    //  Roslyn C# AST Generator
    // ─────────────────────────────────────────────

    private static string GenerateCSharpRecordNodes(
        SchemaNode node,
        string className,
        List<RecordDeclarationSyntax> recordList)
    {
        var recordDecl = SyntaxFactory.RecordDeclaration(
            SyntaxFactory.Token(SyntaxKind.RecordKeyword),
            className)
            .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
            .WithOpenBraceToken(SyntaxFactory.Token(SyntaxKind.OpenBraceToken))
            .WithCloseBraceToken(SyntaxFactory.Token(SyntaxKind.CloseBraceToken));

        foreach (var propKvp in node.Properties)
        {
            string childName = propKvp.Key;
            var childNode = propKvp.Value;
            string sanitizedPropName = SanitizeIdentifier(childName);
            string fieldTypeName;

            if (childNode.Kind == "Object")
            {
                string dtoClassName = $"{sanitizedPropName}Dto";
                GenerateCSharpRecordNodes(childNode, dtoClassName, recordList);
                fieldTypeName = childNode.IsNullable ? $"{dtoClassName}?" : dtoClassName;
            }
            else if (childNode.Kind == "Array")
            {
                string elemType = childNode.ElementNode != null && childNode.ElementNode.Kind == "Object"
                    ? GenerateCSharpRecordNodes(childNode.ElementNode, $"{sanitizedPropName}ItemDto", recordList)
                    : (childNode.ElementNode?.CSharpBaseType ?? "string");

                fieldTypeName = $"{elemType}[]";
                if (childNode.IsNullable) fieldTypeName += "?";
            }
            else
            {
                fieldTypeName = childNode.CSharpBaseType;
                if (childNode.IsNullable && !fieldTypeName.EndsWith('?'))
                {
                    fieldTypeName += "?";
                }
            }

            var propertyDecl = SyntaxFactory.PropertyDeclaration(
                SyntaxFactory.ParseTypeName(fieldTypeName),
                sanitizedPropName)
                .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                .AddAccessorListAccessors(
                    SyntaxFactory.AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                        .WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)),
                    SyntaxFactory.AccessorDeclaration(SyntaxKind.InitAccessorDeclaration)
                        .WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)));

            recordDecl = recordDecl.AddMembers(propertyDecl);
        }

        recordList.Add(recordDecl);
        return className;
    }

    // ─────────────────────────────────────────────
    //  TypeScript Generator
    // ─────────────────────────────────────────────

    private static string GenerateTypeScriptInterfaces(SchemaNode node, string interfaceName, StringBuilder sb)
    {
        // 递归先生成子 DTO 接口
        foreach (var propKvp in node.Properties)
        {
            var childNode = propKvp.Value;
            string sanitizedPropName = SanitizeIdentifier(propKvp.Key);

            if (childNode.Kind == "Object")
            {
                GenerateTypeScriptInterfaces(childNode, $"{sanitizedPropName}Dto", sb);
            }
            else if (childNode.Kind == "Array" && childNode.ElementNode?.Kind == "Object")
            {
                GenerateTypeScriptInterfaces(childNode.ElementNode, $"{sanitizedPropName}ItemDto", sb);
            }
        }

        sb.AppendLine(CultureInfo.InvariantCulture, $"export interface {interfaceName} {{");
        foreach (var propKvp in node.Properties)
        {
            string childName = propKvp.Key;
            var childNode = propKvp.Value;
            string sanitizedPropName = SanitizeIdentifier(childName);
            string optional = childNode.IsNullable ? "?" : "";
            string fieldType;

            if (childNode.Kind == "Object")
            {
                fieldType = $"{sanitizedPropName}Dto";
            }
            else if (childNode.Kind == "Array")
            {
                string elemType = childNode.ElementNode?.Kind == "Object"
                    ? $"{sanitizedPropName}ItemDto"
                    : (childNode.ElementNode?.TsBaseType ?? "string");
                fieldType = $"{elemType}[]";
            }
            else
            {
                fieldType = childNode.TsBaseType;
            }

            string formattedPropName = FormatTsPropertyName(childName);
            sb.AppendLine(CultureInfo.InvariantCulture, $"  {formattedPropName}{optional}: {fieldType};");
        }
        sb.AppendLine("}");
        sb.AppendLine();

        return interfaceName;
    }

    // ─────────────────────────────────────────────
    //  JSON Schema Generator
    // ─────────────────────────────────────────────

    private static JsonObject BuildJsonSchemaProperties(SchemaNode node)
    {
        var propsObj = new JsonObject();
        foreach (var propKvp in node.Properties)
        {
            string childName = propKvp.Key;
            var childNode = propKvp.Value;
            var propDef = new JsonObject();

            if (childNode.Kind == "Object")
            {
                if (childNode.IsNullable)
                    propDef["type"] = new JsonArray { "object", "null" };
                else
                    propDef["type"] = "object";

                propDef["properties"] = BuildJsonSchemaProperties(childNode);
                propDef["required"] = BuildJsonSchemaRequired(childNode);
            }
            else if (childNode.Kind == "Array")
            {
                if (childNode.IsNullable)
                    propDef["type"] = new JsonArray { "array", "null" };
                else
                    propDef["type"] = "array";

                var itemDef = new JsonObject();
                if (childNode.ElementNode?.Kind == "Object")
                {
                    itemDef["type"] = "object";
                    itemDef["properties"] = BuildJsonSchemaProperties(childNode.ElementNode);
                    itemDef["required"] = BuildJsonSchemaRequired(childNode.ElementNode);
                }
                else
                {
                    itemDef["type"] = childNode.ElementNode?.JsonSchemaBaseType ?? "string";
                    if (childNode.ElementNode?.Format != null)
                        itemDef["format"] = childNode.ElementNode.Format;
                }
                propDef["items"] = itemDef;
            }
            else
            {
                if (childNode.IsNullable)
                    propDef["type"] = new JsonArray { childNode.JsonSchemaBaseType, "null" };
                else
                    propDef["type"] = childNode.JsonSchemaBaseType;

                if (childNode.Format != null)
                    propDef["format"] = childNode.Format;
            }

            propsObj[childName] = propDef;
        }
        return propsObj;
    }

    private static JsonArray BuildJsonSchemaRequired(SchemaNode node)
    {
        var reqArray = new JsonArray();
        foreach (var propKvp in node.Properties)
        {
            if (!propKvp.Value.IsNullable)
            {
                reqArray.Add(propKvp.Key);
            }
        }
        return reqArray;
    }

    // ─────────────────────────────────────────────
    //  Type Mapping Helpers
    // ─────────────────────────────────────────────

    private static string MapToCSharpBaseType(FieldStatistic field)
    {
        if (field.SemanticType == "DateTime") return "DateTime";
        if (field.SemanticType == "UUID") return "Guid";
        if (field.PrimaryType == "Number") return field.AvgNumber.HasValue && field.AvgNumber.Value % 1 != 0 ? "double" : "long";
        if (field.PrimaryType == "Boolean") return "bool";
        if (field.PrimaryType == "Array") return "object[]";
        if (field.PrimaryType == "Object") return "object";
        return "string";
    }

    private static string MapToTsBaseType(FieldStatistic field)
    {
        if (field.SemanticType == "DateTime") return "string";
        if (field.PrimaryType == "Number") return "number";
        if (field.PrimaryType == "Boolean") return "boolean";
        if (field.PrimaryType == "Array") return "any[]";
        if (field.PrimaryType == "Object") return "Record<string, any>";
        return "string";
    }

    private static string MapToJsonSchemaBaseType(FieldStatistic field, out string? format)
    {
        format = field.SemanticType switch
        {
            "DateTime" => "date-time",
            "UUID" => "uuid",
            "Email" => "email",
            "IPv4" => "ipv4",
            "URL" => "uri",
            _ => null
        };

        return field.PrimaryType switch
        {
            "Number" => "number",
            "Boolean" => "boolean",
            "Array" => "array",
            "Object" => "object",
            _ => "string"
        };
    }

    private static string SanitizeIdentifier(string fieldName)
    {
        string sanitized = new string(fieldName
            .Select(c => char.IsLetterOrDigit(c) ? c : '_')
            .ToArray());

        if (string.IsNullOrEmpty(sanitized)) return "Property";
        if (char.IsDigit(sanitized[0])) sanitized = "_" + sanitized;

        return char.ToUpperInvariant(sanitized[0]) + sanitized.Substring(1);
    }

    // ─────────────────────────────────────────────
    //  SQL Type Mapping Helpers
    // ─────────────────────────────────────────────

    private static string MapToSqlType(FieldStatistic? field, string dialect)
    {
        if (field == null) return DefaultStringType(dialect);
        if (field.SemanticType == "DateTime") return dialect switch { "sqlite" => "TEXT", "sqlserver" => "DATETIME2", _ => "TIMESTAMP" };
        if (field.SemanticType == "UUID")
        {
            return dialect switch
            {
                "mysql" => "CHAR(36)",
                "sqlite" => "TEXT",
                "sqlserver" => "UNIQUEIDENTIFIER",
                _ => "UUID"
            };
        }

        return field.PrimaryType switch
        {
            "Number" => MapToSqlNumberType(field, dialect),
            "Boolean" => MapToSqlBooleanType(dialect),
            _ => DefaultStringType(dialect)
        };
    }

    private static string MapToSqlNumberType(FieldStatistic field, string dialect)
    {
        bool fractional = field.AvgNumber.HasValue && field.AvgNumber.Value % 1 != 0;
        return dialect switch
        {
            "mysql" => fractional ? "DOUBLE" : "BIGINT",
            "sqlite" => fractional ? "REAL" : "INTEGER",
            "sqlserver" => fractional ? "FLOAT" : "BIGINT",
            _ => fractional ? "DOUBLE PRECISION" : "BIGINT"
        };
    }

    private static string MapToSqlBooleanType(string dialect) => dialect switch
    {
        "mysql" => "TINYINT(1)",
        "sqlite" => "INTEGER",
        "sqlserver" => "BIT",
        _ => "BOOLEAN"
    };

    private static string DefaultStringType(string dialect) => dialect == "sqlserver" ? "NVARCHAR(MAX)" : "TEXT";

    private static string MapToSqlJsonType(string dialect) => dialect switch
    {
        "mysql" => "JSON",
        "sqlite" => "TEXT",
        "sqlserver" => "NVARCHAR(MAX)",
        _ => "JSONB"
    };

    private static string MapDialectDisplayName(string dialect) => dialect switch
    {
        "mysql" => "MySQL",
        "sqlite" => "SQLite",
        "sqlserver" => "SQL Server",
        _ => "PostgreSQL"
    };

    private static string FormatSqlLiteral(JsonElement element, string dialect)
    {
        switch (element.ValueKind)
        {
            case JsonValueKind.String:
                return "'" + (element.GetString() ?? "").Replace("'", "''") + "'";
            case JsonValueKind.Number:
                return element.GetRawText() ?? "0";
            case JsonValueKind.True:
            case JsonValueKind.False:
                bool b = element.GetBoolean();
                return dialect == "postgres" ? (b ? "TRUE" : "FALSE") : (b ? "1" : "0");
            default:
                return "NULL";
        }
    }

    private static string SanitizeSqlIdentifier(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return "";
        string sanitized = new string(name.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
        if (char.IsDigit(sanitized[0])) sanitized = "_" + sanitized;
        return sanitized;
    }

    private static string QuoteIdentifier(string name, string quoteChar)
    {
        if (quoteChar == "`") return "`" + name.Replace("`", "``") + "`";
        if (quoteChar == "[") return "[" + name.Replace("]", "]]") + "]";
        return "\"" + name.Replace("\"", "\"\"") + "\"";
    }

    private static string SqlTableNameFromPath(string outputPath)
    {
        if (string.IsNullOrWhiteSpace(outputPath)) return "GeneratedSchema";
        string name = SanitizeSqlIdentifier(Path.GetFileNameWithoutExtension(outputPath));
        if (name.EndsWith("_schema", StringComparison.OrdinalIgnoreCase))
        {
            name = name.Substring(0, name.Length - "_schema".Length);
        }
        return string.IsNullOrEmpty(name) ? "GeneratedSchema" : name;
    }

    private static string FormatTsPropertyName(string name)
    {
        if (string.IsNullOrEmpty(name)) return "\"\"";
        bool isValid = (char.IsLetter(name[0]) || name[0] == '_' || name[0] == '$') &&
                       name.All(c => char.IsLetterOrDigit(c) || c == '_' || c == '$');
        return isValid ? name : $"\"{name}\"";
    }
