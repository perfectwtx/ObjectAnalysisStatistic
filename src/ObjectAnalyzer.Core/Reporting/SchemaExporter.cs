    /// <summary>
    /// Generates a CREATE TABLE statement for the requested SQL dialect (postgres / mysql / sqlite).
    /// Root-level object/array fields collapse into a dialect-appropriate JSON column;
    /// primitive fields map to typed columns (BIGINT / TEXT / BOOLEAN / TIMESTAMP / UUID ...).
    /// NOT NULL is emitted when a field is present across all objects (coverage 1.0) with no observed null.
    /// A CHECK (col IN (...)) constraint is emitted when the field carries enum rule values.
    /// </summary>
    public static string GenerateSql(AnalysisResult result, string dialect = "postgres", string tableName = "GeneratedSchema")
    {
        var rootTree = BuildSchemaTree(result);
        string normalized = dialect.ToLowerInvariant();
        string quote = normalized switch { "mysql" => "`", "sqlserver" => "[", _ => "\"" };
        string safeTable = SanitizeSqlIdentifier(tableName);
        if (string.IsNullOrEmpty(safeTable)) safeTable = "GeneratedSchema";

        var columnLines = new List<string>();
        var checkLines = new List<string>();
        var usedColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var propKvp in rootTree.Properties)
        {
            var child = propKvp.Value;
            bool isJson = child.Kind == "Object" || child.Kind == "Array";
            string sqlType = isJson ? MapToSqlJsonType(normalized) : MapToSqlType(child.Field, normalized);

            string baseCol = SanitizeSqlIdentifier(propKvp.Key);
            if (string.IsNullOrEmpty(baseCol)) baseCol = "column";
            string colName = baseCol;
            int suffix = 2;
            while (!usedColumns.Add(colName)) colName = baseCol + "_" + suffix++.ToString(CultureInfo.InvariantCulture);
            string col = QuoteIdentifier(colName, quote);

            bool notNull = child.Field != null && child.Field.Coverage >= 1.0 && !child.Field.NullAppeared;
            columnLines.Add($"{col} {sqlType}{(notNull ? " NOT NULL" : "")}");

            if (!isJson && child.Field?.AppliedRule?.EnumValues is { Count: > 0 } enumValues)
            {
                var literals = enumValues
                    .Select(e => FormatSqlLiteral(e, normalized))
                    .Distinct(StringComparer.Ordinal)
                    .ToList();
                if (literals.Count > 0)
                {
                    checkLines.Add($"CHECK ({col} IN ({string.Join(", ", literals)}))");
                }
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("-- <auto-generated>");
        sb.AppendLine(CultureInfo.InvariantCulture, $"-- ObjectAnalyzer 自动生成的 {MapDialectDisplayName(normalized)} Schema");
        sb.AppendLine("-- </auto-generated>");
        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"CREATE TABLE {QuoteIdentifier(safeTable, quote)} (");

        var body = new List<string>();
        body.AddRange(columnLines);
        body.AddRange(checkLines);
        for (int i = 0; i < body.Count; i++)
        {
            string suffix = i < body.Count - 1 ? "," : "";
            sb.AppendLine(CultureInfo.InvariantCulture, $"  {body[i]}{suffix}");
        }

        sb.AppendLine(");");
        return sb.ToString();
    }

