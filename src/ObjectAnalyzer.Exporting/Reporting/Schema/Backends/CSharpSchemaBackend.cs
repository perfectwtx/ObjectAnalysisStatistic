using System.Text;
using System.Text.Json;
using ObjectAnalyzer.Data;

namespace ObjectAnalyzer.Reporting;

public sealed class CSharpSchemaBackend : ISchemaBackend
{
    public string Format => "csharp";
    public SchemaExportResult Generate(SchemaDocument document, SchemaExportOptions options)
    {
        var context = new SchemaRenderContext(document, options);
        var names = SchemaNamePlan.Create(document, SchemaNamingTarget.CSharp, options.RootName);
        var output = new StringBuilder("#nullable enable\nusing System;\n\nnamespace ObjectAnalyzer.Generated;\n\n");
        foreach (var node in names.Objects)
        {
            output.Append("public record ").Append(names.TypeName(node)).AppendLine(" {");
            foreach (var property in node.Properties.OrderBy(item => item.Name, StringComparer.Ordinal))
            {
                string type = Type(property.Type, SchemaRenderContext.Child(names.SourcePath(node), property.Name), names, context);
                if (property.Presence != SchemaPresence.Required)
                {
                    if (!type.EndsWith('?')) type += "?";
                    if (!property.Type.AllowsNull) context.Note("csharp-optional-null", SchemaRenderContext.Child(names.SourcePath(node), property.Name), "Missing properties use nullable CLR storage; JSON missing and null cannot be distinguished by this property alone.");
                }
                output.Append("  [System.Text.Json.Serialization.JsonPropertyName(").Append(JsonSerializer.Serialize(property.Name)).AppendLine(")]");
                if (property.Presence == SchemaPresence.Required) output.AppendLine("  [System.Text.Json.Serialization.JsonRequired]");
                output.Append("  public ").Append(type).Append(' ').Append(names.PropertyName(node, property.Name)).AppendLine(" { get; init; } = default!;");
            }
            output.AppendLine("  [System.Text.Json.Serialization.JsonExtensionData]");
            var usedNames = new HashSet<string>(node.Properties.Select(property => property.Name)
                .Concat(node.Properties.Select(property => names.PropertyName(node, property.Name))).Append(names.TypeName(node)), StringComparer.Ordinal);
            string extension = SchemaNamePlan.Allocate("AdditionalProperties", usedNames);
            output.Append("  public System.Collections.Generic.Dictionary<string, System.Text.Json.JsonElement>? ").Append(extension).AppendLine(" { get; init; }");
            output.AppendLine("}").AppendLine();
        }
        return context.Finish("// <auto-generated>\n" + context.Comments("//") + output);
    }
    private static string Type(SchemaType node, string path, SchemaNamePlan names, SchemaRenderContext context)
    {
        if (node.EnumValues.Length > 0) context.Note("csharp-enum-unenforced", path, "CLR property types do not enforce declared enum constraints; validate input with the exported schema.");
        var kinds = node.Kinds.Where(kind => kind != RecordValueKind.Null).ToArray();
        string type;
        if (node.HasUnknownValues || node.ShapeIncomplete || kinds.Length != 1)
        {
            type = "System.Text.Json.JsonElement";
            context.Note("csharp-dynamic", path, "Unknown or heterogeneous evidence uses JsonElement instead of discarding variants.");
        }
        else type = kinds[0] switch
        {
            RecordValueKind.Object => names.TypeName(node),
            RecordValueKind.Array => Element(node, path, names, context) + "[]",
            RecordValueKind.Number => node.Numeric is { Integral: true, FitsInt64: true } ? "long"
                : node.Numeric?.FitsDouble == true ? "double" : node.Numeric?.FitsDecimal == true ? "decimal" : DynamicNumber(path, context),
            RecordValueKind.Boolean => "bool",
            RecordValueKind.DateTime => "DateTime", RecordValueKind.DateTimeOffset => "DateTimeOffset",
            RecordValueKind.Date => "DateOnly", RecordValueKind.Time => "TimeOnly", RecordValueKind.Duration => "TimeSpan",
            RecordValueKind.Guid => "Guid", RecordValueKind.Binary => "byte[]",
            _ => node.VerifiedSemanticTypes.Length == 1 && node.VerifiedSemanticTypes[0] == "UUID" ? "Guid"
                : node.VerifiedSemanticTypes.Length == 1 && node.VerifiedSemanticTypes[0] == "DateTime" ? "DateTimeOffset" : "string"
        };
        return node.AllowsNull ? type + "?" : type;
    }
    private static string Element(SchemaType node, string path, SchemaNamePlan names, SchemaRenderContext context)
    {
        if (node.Element is not null) return Type(node.Element, path + "[]", names, context);
        context.Note("array-element-unknown", path, "An empty or unobserved array does not establish an element type; using JsonElement.");
        return "System.Text.Json.JsonElement";
    }
    private static string DynamicNumber(string path, SchemaRenderContext context)
    {
        context.Note("csharp-number-precision", path, "Number does not fit Int64, decimal or round-trippable double; preserving its JSON number with JsonElement.");
        return "System.Text.Json.JsonElement";
    }
}
