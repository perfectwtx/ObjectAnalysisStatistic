using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json.Nodes;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ObjectAnalyzer;

/// <summary>
/// Exports inferred object schemas based on analysis results to
/// C# record/class (via Roslyn SyntaxFactory AST), TypeScript interface, or JSON Schema (via System.Text.Json.Nodes DOM).
/// </summary>
public static class SchemaExporter
{
    public static void Export(AnalysisResult result, string format, string outputPath)
    {
        string content = format.ToLowerInvariant() switch
        {
            "csharp" or "cs" => GenerateCSharp(result),
            "typescript" or "ts" => GenerateTypeScript(result),
            "json-schema" or "jsonschema" or "schema" => GenerateJsonSchema(result),
            _ => throw new InvalidOperationException($"不支持的 Schema 导出格式: '{format}'。可用格式: csharp, typescript, json-schema")
        };

        File.WriteAllText(outputPath, content, Encoding.UTF8);
    }

    /// <summary>
    /// Generates C# record declaration code using Roslyn SyntaxFactory AST nodes.
    /// Guarantees 100% syntactically valid and clean formatted C# code with braces {}.
    /// </summary>
    public static string GenerateCSharp(AnalysisResult result, string className = "GeneratedSchema")
    {
        // 1. 构建文件级命名空间节点: namespace ObjectAnalyzer.Generated;
        var namespaceDecl = SyntaxFactory.FileScopedNamespaceDeclaration(
            SyntaxFactory.ParseName("ObjectAnalyzer.Generated"));

        // 2. 构建 record 节点并显式添加 { 和 } 大括号: public record ClassName { ... }
        var recordDecl = SyntaxFactory.RecordDeclaration(
            SyntaxFactory.Token(SyntaxKind.RecordKeyword),
            className)
            .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
            .WithOpenBraceToken(SyntaxFactory.Token(SyntaxKind.OpenBraceToken))
            .WithCloseBraceToken(SyntaxFactory.Token(SyntaxKind.CloseBraceToken));

        // 3. 为每个字段构建 Property 属性语法树节点
        foreach (var field in result.FieldStatistics)
        {
            string propName = SanitizeIdentifier(field.FieldName);
            string csTypeName = MapToCSharpType(field);

            // 构建属性节点: public csTypeName propName { get; init; }
            var propertyDecl = SyntaxFactory.PropertyDeclaration(
                SyntaxFactory.ParseTypeName(csTypeName),
                propName)
                .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                .AddAccessorListAccessors(
                    SyntaxFactory.AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                        .WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)),
                    SyntaxFactory.AccessorDeclaration(SyntaxKind.InitAccessorDeclaration)
                        .WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)));

            recordDecl = recordDecl.AddMembers(propertyDecl);
        }

        namespaceDecl = namespaceDecl.AddMembers(recordDecl);

        // 4. 构建包含 using System; 的顶层语法树单元
        var compilationUnit = SyntaxFactory.CompilationUnit()
            .AddUsings(SyntaxFactory.UsingDirective(SyntaxFactory.ParseName("System")))
            .AddMembers(namespaceDecl);

        // 5. 调用 Roslyn 节点规范排版器，美化为带 {} 大括号的标准代码文本
        string formattedCode = compilationUnit.NormalizeWhitespace().ToFullString();

        return "// <auto-generated>\n// 由 ObjectAnalyzer (Roslyn SyntaxFactory AST) 自动生成\n// </auto-generated>\n\n" + formattedCode;
    }

    public static string GenerateTypeScript(AnalysisResult result, string interfaceName = "GeneratedSchema")
    {
        var sb = new StringBuilder();
        sb.AppendLine("/**");
        sb.AppendLine(" * 由 ObjectAnalyzer 自动生成的 TypeScript 接口声明");
        sb.AppendLine(" */");
        sb.AppendLine(CultureInfo.InvariantCulture, $"export interface {interfaceName} {{");

        foreach (var field in result.FieldStatistics)
        {
            string propName = field.FieldName;
            string optional = field.NullAppeared ? "?" : "";
            string tsType = MapToTypeScriptType(field);
            sb.AppendLine(CultureInfo.InvariantCulture, $"  {propName}{optional}: {tsType};");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates standard JSON Schema specification using System.Text.Json.Nodes DOM.
    /// Guarantees valid JSON escaping and structural integrity without manual string concatenation.
    /// </summary>
    public static string GenerateJsonSchema(AnalysisResult result)
    {
        var properties = new JsonObject();
        var required = new JsonArray();

        foreach (var field in result.FieldStatistics)
        {
            var propDef = new JsonObject();
            string jsonType = MapToJsonSchemaType(field, out string? format);

            if (field.NullAppeared)
            {
                propDef["type"] = new JsonArray { jsonType, "null" };
            }
            else
            {
                propDef["type"] = jsonType;
                required.Add(field.FieldName);
            }

            if (format != null)
            {
                propDef["format"] = format;
            }

            if (!string.IsNullOrEmpty(field.DefaultValueRepresentation))
            {
                propDef["default"] = field.DefaultValueRepresentation;
            }

            properties[field.FieldName] = propDef;
        }

        var schemaRoot = new JsonObject
        {
            ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
            ["title"] = "GeneratedSchema",
            ["type"] = "object",
            ["properties"] = properties,
            ["required"] = required
        };

        return schemaRoot.ToJsonString(JsonSharedOptions.Write);
    }

    private static string MapToCSharpType(FieldStatistic field)
    {
        string baseType;

        if (field.SemanticType == "DateTime") baseType = "DateTime";
        else if (field.SemanticType == "UUID") baseType = "Guid";
        else if (field.PrimaryType == "Number") baseType = field.AvgNumber.HasValue && field.AvgNumber.Value % 1 != 0 ? "double" : "long";
        else if (field.PrimaryType == "Boolean") baseType = "bool";
        else if (field.PrimaryType == "Array") baseType = "object[]";
        else if (field.PrimaryType == "Object") baseType = "object";
        else baseType = "string";

        if (field.NullAppeared)
        {
            return $"{baseType}?";
        }

        return baseType;
    }

    private static string MapToTypeScriptType(FieldStatistic field)
    {
        if (field.SemanticType == "DateTime") return "string";
        if (field.PrimaryType == "Number") return "number";
        if (field.PrimaryType == "Boolean") return "boolean";
        if (field.PrimaryType == "Array") return "any[]";
        if (field.PrimaryType == "Object") return "Record<string, any>";
        return "string";
    }

    private static string MapToJsonSchemaType(FieldStatistic field, out string? format)
    {
        format = field.SemanticType switch
        {
            "DateTime" => "date-time",
            "UUID" => "uuid",
            "Email" => "email",
            "IPv4" => "ipv4",
            "URL" => "uri",
            _ => null
        };

        return field.PrimaryType switch
        {
            "Number" => "number",
            "Boolean" => "boolean",
            "Array" => "array",
            "Object" => "object",
            _ => "string"
        };
    }

    private static string SanitizeIdentifier(string fieldName)
    {
        string sanitized = new string(fieldName
            .Select(c => char.IsLetterOrDigit(c) ? c : '_')
            .ToArray());

        if (string.IsNullOrEmpty(sanitized)) return "Property";
        if (char.IsDigit(sanitized[0])) sanitized = "_" + sanitized;

        return char.ToUpperInvariant(sanitized[0]) + sanitized.Substring(1);
    }
}
